import { chromium } from '@playwright/test';
import path from 'node:path';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3000/',{waitUntil:'networkidle'});
await page.evaluate(async()=>{await Promise.all(Array.from(document.images).map(im=>{im.loading='eager';return im.decode().catch(()=>{});}));});
await page.waitForTimeout(1800);
await page.screenshot({path:path.resolve('../preview-desktop.png'),fullPage:true});
await page.screenshot({path:path.resolve('../preview-hero.png')});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:path.resolve('../preview-mobile.png'),fullPage:true});
console.log(JSON.stringify({errors,title:await page.title()}));
await browser.close();
